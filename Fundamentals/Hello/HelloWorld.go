package main

import (
	"fmt"
)

func main() {

	// Variable Declaration with inicial Value
	var std1 string = "Jhon"
	var std2 = "Zihad"
	x := 2

	fmt.Println(std1)
	fmt.Println(std2)
	fmt.Println(x)

	// Variable Declaration without inicial Value
	var a string
	var b int
	var c bool

	fmt.Println(a)
	fmt.Println(b)
	fmt.Println(c)

}
