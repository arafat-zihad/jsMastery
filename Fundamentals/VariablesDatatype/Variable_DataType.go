package main

import "fmt"

func main() {
	// Declaring and initializing a variable
	var a int = 10
	fmt.Println("Value of a:", a)

	// Let's demonstrate more variable concepts
	var b = 20 // Type inference
	c := 30    // Short declaration

	fmt.Println("Value of b:", b)
	fmt.Println("Value of c:", c)
}
